
CREATE TABLE tax_jurisdictions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    name VARCHAR(100) NOT NULL,
    base_rate NUMERIC(10, 4) NOT NULL,
    effective_date DATE NOT NULL
);

CREATE INDEX idx_jurisdiction_code
    ON tax_jurisdictions(code);

CREATE TABLE fuel_tax_calculations (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shipment_id VARCHAR(100) NOT NULL,
    jurisdiction_id BIGINT NOT NULL,
    fuel_quantity NUMERIC(12, 3) NOT NULL,
    price_per_gallon NUMERIC(12, 4) NOT NULL,
    calculated_tax NUMERIC(14, 4) NOT NULL,
    calculated_on TIMESTAMP NOT NULL,

    CONSTRAINT fk_calculation_jurisdiction
        FOREIGN KEY (jurisdiction_id)
        REFERENCES tax_jurisdictions(id)
);

CREATE INDEX idx_calculation_shipment
    ON fuel_tax_calculations(shipment_id);
